# Build FtdcNet.CTP and publish the nupkg to a local NuGet folder feed.
# Release only: FtdcNet.CTP.csproj packages natives from ..\Release\runtimes,
# so a Debug package would ship without the native DLLs.
param(
    [string]$OutputDir = "C:\Works\LocalNuGet",
    [switch]$SkipBuild,
    [switch]$Force
)

$ErrorActionPreference = "Stop"

$RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
$ManagedDir = Join-Path $RepoRoot "FtdcNet.CTP"
$BinDir = Join-Path $ManagedDir "bin\Release"
$NativeDir = Join-Path $RepoRoot "Release\runtimes"
$buildStart = $null

if (-not $SkipBuild) {
    $buildStart = Get-Date
    Write-Host "== Full rebuild (native x64/x86 + ABI/layout checks + managed)"
    & (Join-Path $PSScriptRoot "build.ps1") -Configuration Release
}

$nupkg = Get-ChildItem -Path $BinDir -Filter "FtdcNet.CTP.*.nupkg" -File |
    Where-Object { $_.Extension -eq ".nupkg" } |
    Sort-Object LastWriteTime -Descending | Select-Object -First 1
if (-not $nupkg) {
    throw "No FtdcNet.CTP.*.nupkg found under $BinDir. Run without -SkipBuild."
}

# Guard against publishing a package that predates the current sources/natives.
$problems = @()
if (-not $SkipBuild -and $nupkg.LastWriteTime -lt $buildStart.AddSeconds(-5)) {
    $problems += "nupkg was not regenerated by this build (LastWriteTime $($nupkg.LastWriteTime))"
}
$inputs = @(Get-ChildItem -Path $ManagedDir -Filter "*.cs" -File)
$inputs += Get-Item (Join-Path $ManagedDir "FtdcNet.CTP.csproj")
if (Test-Path $NativeDir) {
    $inputs += Get-ChildItem -Path $NativeDir -Recurse -Filter "*.dll" -File
}
$newestInput = $inputs | Sort-Object LastWriteTime -Descending | Select-Object -First 1
if ($newestInput -and $nupkg.LastWriteTime -lt $newestInput.LastWriteTime) {
    $problems += "nupkg ($($nupkg.LastWriteTime)) is older than $($newestInput.FullName) ($($newestInput.LastWriteTime))"
}
if ($problems.Count -gt 0) {
    if ($Force) {
        foreach ($p in $problems) { Write-Warning $p }
    } else {
        throw ("Stale package: " + ($problems -join "; ") + ". Re-run without -SkipBuild, or pass -Force.")
    }
}

if ($nupkg.Name -notmatch '^FtdcNet\.CTP\.(?<ver>\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?)\.nupkg$') {
    throw "Unexpected package file name: $($nupkg.Name)"
}
$version = $Matches["ver"]

Write-Host "== Verify package contents"
Add-Type -AssemblyName System.IO.Compression.FileSystem
$required = @(
    "lib/net40/FtdcNet.CTP.dll",
    "lib/net40/FtdcNet.CTP.xml",
    "lib/netstandard2.0/FtdcNet.CTP.dll",
    "lib/netstandard2.0/FtdcNet.CTP.xml",
    "runtimes/win-x64/native/WinDataCollect.dll",
    "runtimes/win-x64/native/ftdc2c_ctp.dll",
    "runtimes/win-x64/native/thostmduserapi_se.dll",
    "runtimes/win-x64/native/thosttraderapi_se.dll",
    "runtimes/win-x86/native/ftdc2c_ctp.dll",
    "runtimes/win-x86/native/thostmduserapi_se.dll",
    "runtimes/win-x86/native/thosttraderapi_se.dll"
)
$zip = [System.IO.Compression.ZipFile]::OpenRead($nupkg.FullName)
try {
    $entries = @($zip.Entries | ForEach-Object { $_.FullName.ToLowerInvariant() })
    $missing = @($required | Where-Object { $entries -notcontains $_.ToLowerInvariant() })
    $nativeCount = @($zip.Entries |
        Where-Object { $_.FullName -match '^runtimes/win-(x64|x86)/native/[^/]+\.dll$' }).Count
} finally {
    $zip.Dispose()
}
if ($missing.Count -gt 0) {
    throw "Package is missing: $($missing -join ', ')"
}
if ($nativeCount -ne 7) {
    throw "Expected exactly 7 native DLLs in the package, found $nativeCount"
}

Write-Host "== Publish to $OutputDir"
New-Item -ItemType Directory -Force -Path $OutputDir | Out-Null
$dest = Join-Path $OutputDir $nupkg.Name
Copy-Item -Force $nupkg.FullName $dest

$snupkgSrc = Join-Path $BinDir ("FtdcNet.CTP.$version.snupkg")
if (Test-Path $snupkgSrc) {
    Copy-Item -Force $snupkgSrc (Join-Path $OutputDir "FtdcNet.CTP.$version.snupkg")
} else {
    Write-Warning "Symbol package not found at $snupkgSrc"
}

$hash = (Get-FileHash -Algorithm SHA256 $dest).Hash

Write-Host ""
Write-Host "== Local package ready"
Write-Host "   Package : $dest"
Write-Host "   Version : $version"
Write-Host "   SHA256  : $hash"
Write-Host ""
Write-Host "Register the feed once per machine:"
Write-Host "   dotnet nuget add source `"$OutputDir`" -n FtdcNetLocal"
Write-Host "Install into a consumer project:"
Write-Host "   dotnet add package FtdcNet.CTP --version $version"
Write-Host ""
Write-Host "Note: NuGet caches by package id + version. If $version was restored before"
Write-Host "(e.g. from nuget.org), delete %USERPROFILE%\.nuget\packages\ftdcnet.ctp\$version"
Write-Host "and run 'dotnet restore --force'."
